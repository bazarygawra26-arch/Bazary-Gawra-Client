export async function findExhibitionBySlug(slug: string): Promise<Exhibition | null> {
  const normalized = slug?.toLowerCase()?.trim();
  const match = fallbackExhibitions.find(
    (e) =>
      e.slug.toLowerCase() === normalized ||
      e.id.toLowerCase() === normalized ||
      normalized.includes(e.slug.toLowerCase()) ||
      e.slug.toLowerCase().includes(normalized)
  );

  return match || fallbackExhibitions[0] || null;
}
